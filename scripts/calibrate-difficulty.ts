/**
 * Measures how hard the Tandem Clash rival is at every point on its strength ladder, for each challenge
 * rarity, and writes src/tcg/difficulty-curves.ts. The admin "target win rate" setting reads that file.
 *
 * Run it again whenever the scoring, the Crew cards, the debuffs or the AI change:
 *
 *   # one rarity at a time (slow, so run these side by side):
 *   for t in bronze silver gold legend mythic; do
 *     BATTLES=1200 npx tsx --tsconfig tsconfig.json scripts/calibrate-difficulty.ts measure $t > /tmp/curve-$t.json &
 *   done; wait
 *   # then join them into the file the app reads:
 *   npx tsx --tsconfig tsconfig.json scripts/calibrate-difficulty.ts write
 */
import { readFileSync, writeFileSync } from "node:fs";
import type { FullArtTier } from "@/lib/full-art-card";
import { DEFAULT_SIM, winRate } from "@/tcg/battle-sim";
import { LADDER_POINTS, ladderDials } from "@/tcg/rival-ai";

const TIERS: FullArtTier[] = ["bronze", "silver", "gold", "legend", "mythic"];
const BATTLES = Number(process.env.BATTLES ?? 1200);

const mode = process.argv[2];
if (mode === "measure") {
  const tier = process.argv[3] as FullArtTier;
  const points: Array<[number, number]> = [];
  for (const strength of LADDER_POINTS) {
    const d = ladderDials(strength);
    const cfg = { ...DEFAULT_SIM, tier, rival: "ai" as const, skill: d.skill, rivalCarSkip: d.carSkip, rivalCrewCount: d.crewCount, rivalCrewBoost: d.crewBoost };
    // A typical player is half casual, half good.
    const casual = winRate({ ...cfg, player: "casual" }, BATTLES, 101);
    const good = winRate({ ...cfg, player: "good" }, BATTLES, 202);
    points.push([strength, Math.round(((casual + good) / 2) * 1000) / 1000]);
    console.error(`${tier} strength ${strength}: ${(((casual + good) / 2) * 100).toFixed(1)}%`);
  }
  console.log(JSON.stringify(points));
} else if (mode === "write") {
  const curves: Record<string, Array<[number, number]>> = {};
  for (const tier of TIERS) {
    try {
      curves[tier] = JSON.parse(readFileSync(`/tmp/curve-${tier}.json`, "utf8"));
    } catch {
      console.error(`No measurement for ${tier} (run "measure ${tier}" first); skipping it.`);
    }
  }
  const body = Object.entries(curves)
    .map(([tier, points]) => `  ${tier}: ${JSON.stringify(points)},`)
    .join("\n");
  writeFileSync(
    "src/tcg/difficulty-curves.ts",
    `// GENERATED by scripts/calibrate-difficulty.ts (${BATTLES} battles per player type per point). Do not edit by hand; run the script again instead.
// For each rarity: [rival strength, how often a typical player wins] at each point on the strength ladder.
export const WIN_RATE_CURVES: Record<string, Array<[number, number]>> = {
${body}
};
`
  );
  console.log("Wrote src/tcg/difficulty-curves.ts");
} else {
  console.log("Usage: calibrate-difficulty.ts measure <rarity>  |  calibrate-difficulty.ts write");
}
